create or replace function public.adjust_inventory_item(
  p_tenant_id varchar,
  p_item_id bigint,
  p_change_amount integer,
  p_reason varchar,
  p_performed_by varchar
)
returns setof public.inventory_items
language plpgsql
security definer
as $$
declare
  v_item public.inventory_items%rowtype;
  v_next_qty integer;
begin
  if p_change_amount = 0 then
    raise exception 'change_amount cannot be zero' using errcode = '23514';
  end if;

  select *
  into v_item
  from public.inventory_items
  where id = p_item_id and tenant_id = p_tenant_id
  for update;

  if not found then
    raise exception 'Inventory item not found' using errcode = '23503';
  end if;

  v_next_qty := v_item.quantity_on_hand + p_change_amount;
  if v_next_qty < 0 then
    raise exception 'Adjustment would result in negative stock' using errcode = '23514';
  end if;

  update public.inventory_items
  set quantity_on_hand = v_next_qty,
      updated_at = timezone('utc', now())
  where id = v_item.id;

  insert into public.inventory_movements (item_id, tenant_id, change_amount, reason, performed_by)
  values (v_item.id, p_tenant_id, p_change_amount, p_reason, coalesce(p_performed_by, ''));

  return query
  select *
  from public.inventory_items
  where id = v_item.id;
end;
$$;

