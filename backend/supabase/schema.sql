create or replace function public.same_tenant_access(target_tenant_id varchar)
returns boolean
language sql
stable
as $$
  select exists (
    select 1
    from public.tenant_memberships membership
    where membership.user_id = coalesce(nullif(auth.jwt() ->> 'app_user_id', '')::bigint, -1)
      and membership.tenant_id = target_tenant_id
      and membership.is_active = 1
  );
$$;

